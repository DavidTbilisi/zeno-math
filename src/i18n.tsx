const DICTS: Record<Lang, Dict> = { en, ru, ka };

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "ru" || saved === "ka") return saved;
  } catch {
    /* storage unavailable */
  }
  const nav = navigator.language.slice(0, 2);
  return nav === "ru" || nav === "ka" ? nav : "en";
}

type I18n = { lang: Lang; setLang: (l: Lang) => void; t: Dict; excalidrawLang: string };

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const setLang = (l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("lang", l);
    } catch {
      /* storage unavailable */
    }
  };
  const excalidrawLang = LANGS.find((l) => l.code === lang)!.excalidraw;
  return <I18nContext.Provider value={{ lang, setLang, t: DICTS[lang], excalidrawLang }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}

export function LangSelect() {
  const { lang, setLang, t } = useI18n();
  return (
    <select className="lang-select" aria-label={t.language} value={lang} onChange={(e) => setLang(e.target.value as Lang)}>
      {LANGS.map((l) => (
        <option key={l.code} value={l.code}>
          {l.label}
        </option>
      ))}
    </select>
  );
}
